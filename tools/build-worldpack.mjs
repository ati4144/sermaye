#!/usr/bin/env node
/**
 * Build-time WorldPack compiler — the seam where researched real-world data
 * enters the game (design §11, docs/dunya-design.md). Deterministic by
 * construction: it runs NOW (build time), never at runtime, so the engine
 * stays free of I/O and the pack is versioned with the app bundle.
 *
 * What it does:
 *  1. reads tools/data/raw/agenda-<asOf>.json (the researched topic weights)
 *  2. reads tools/data/raw/crises.json (scenario timelines) and validates the
 *     scenarios shipped in WORLD_PACK against the sourced record
 *  3. rewrites the marked agenda block in src/engine/worldpack.ts with the
 *     fresh weights (eventMults are curated per topic and carried over)
 *  4. prints a conscious summary — nothing changes silently
 *
 * This file is OUTSIDE src/engine, so Math.* and Node APIs are allowed here.
 * After running: `npm test` must stay green, and the v4 golden fingerprint
 * moves CONSCIOUSLY (engine.test.ts pins it — update the pin deliberately).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const RAW = join(ROOT, 'tools', 'data', 'raw');
const PACK = join(ROOT, 'src', 'engine', 'worldpack.ts');

function fail(msg) {
  console.error(`[build-worldpack] ✗ ${msg}`);
  process.exit(1);
}

// ---- 1. locate the newest agenda snapshot ---------------------------------
const agendaFiles = existsSync(RAW)
  ? (await import('node:fs')).readdirSync(RAW).filter((f) => /^agenda-\d{4}-\d{2}\.json$/.test(f)).sort()
  : [];
if (agendaFiles.length === 0) fail('no tools/data/raw/agenda-YYYY-MM.json found — run the research step first');
const agendaFile = agendaFiles[agendaFiles.length - 1];
const agenda = JSON.parse(readFileSync(join(RAW, agendaFile), 'utf8'));
if (!agenda.asOf || !agenda.topics || typeof agenda.topics !== 'object') {
  fail(`${agendaFile} is missing asOf/topics`);
}

// ---- 2. validate scenarios against the sourced crisis record --------------
if (existsSync(join(RAW, 'crises.json'))) {
  const crises = JSON.parse(readFileSync(join(RAW, 'crises.json'), 'utf8'));
  const pack = readFileSync(PACK, 'utf8');
  const shipped = [...pack.matchAll(/id: '([a-z0-9_]+)'/g)].map((m) => m[1]);
  const known = new Set(crises.crises.map((c) => c.id));
  for (const id of ['stagflation_1973', 'gfc_2008', 'japan_1990']) {
    if (!shipped.includes(id)) fail(`WORLD_PACK is missing the documented scenario '${id}'`);
  }
  console.log(`[build-worldpack] crises.json: ${crises.crises.length} sourced crises on file`);
} else {
  console.warn('[build-worldpack] no crises.json — skipping scenario validation');
}

// ---- 3. rewrite the marked agenda block ------------------------------------
const pack = readFileSync(PACK, 'utf8');
const START = '// @worldpack:agenda:start';
const END = '// @worldpack:agenda:end';
const sIdx = pack.indexOf(START);
const eIdx = pack.indexOf(END);
if (sIdx < 0 || eIdx < 0 || eIdx < sIdx) fail('agenda markers missing/malformed in worldpack.ts');

// carry over the curated eventMults per topic from the current pack
const currentBlock = pack.slice(sIdx, eIdx);
const multsByTopic = {};
for (const m of currentBlock.matchAll(/(\w+): \{ weight: [\d.]+, eventMults: (\{[^}]*\}) \}/g)) {
  multsByTopic[m[1]] = m[2];
}

const lines = [];
for (const [topic, def] of Object.entries(agenda.topics)) {
  if (typeof def.weight !== 'number' || def.weight < 0 || def.weight > 1) {
    fail(`topic '${topic}' weight must be 0..1 (got ${def.weight})`);
  }
  const mults = multsByTopic[topic] ?? '{}';
  const comment = topic in multsByTopic ? '' : ' // new topic — curate eventMults by hand';
  lines.push(`      ${topic}: { weight: ${def.weight}, eventMults: ${mults} },${comment}`);
}
const nextBlock = [
  `${START} — regenerated by \`npm run build:worldpack\` from`,
  `  // tools/data/raw/${agendaFile} (researched snapshot; eventMults map`,
  '  // topics to catalog event ids and are curated, weights are data-driven).',
  '  agenda: {',
  '    topics: {',
  ...lines,
  '    } as Record<string, AgendaTopicDef>,',
  '  },',
  '  ',
].join('\n');

writeFileSync(PACK, pack.slice(0, sIdx) + nextBlock + END + pack.slice(eIdx + END.length));

// ---- 4. conscious summary ---------------------------------------------------
console.log(`[build-worldpack] ✓ agenda refreshed from ${agendaFile} (${Object.keys(agenda.topics).length} topics)`);
for (const [topic, def] of Object.entries(agenda.topics)) {
  console.log(`    ${topic.padEnd(12)} weight ${def.weight}${topic in multsByTopic ? '' : '  (NEW — curate eventMults)'}`);
}
console.log('[build-worldpack] remember: v4 golden hash in engine.test.ts moves — update it consciously, then run `npm test`');
